// Builds public/assets/js/moon-hero.js from scripts/moon-hero/scene.ts, with only the parts of
// three.js it uses. Self-hosted so the homepage needs no third-party script host (the site's CSP
// allows 'self'). Run: npm run build:moon-hero, then commit the bundle and landing.html together.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { MOON_HERO_BUNDLE, MOON_HERO_SOURCES, moonHeroSourceHash } from './source-hash.mjs';

const hash = moonHeroSourceHash();
const result = await build({
  entryPoints: ['scripts/moon-hero/scene.ts'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2020'],
  legalComments: 'inline', // keeps three.js's MIT licence notice
  write: false,
});
const banner = `/* GENERATED by scripts/moon-hero/build.mjs from ${MOON_HERO_SOURCES.join(', ')}; source hash ${hash}. Do not edit; run npm run build:moon-hero. */\n`;
writeFileSync(MOON_HERO_BUNDLE, banner + result.outputFiles[0].text);

// Point the homepage at this build so browsers do not keep an old copy.
const landingPath = 'public/landing.html';
const landing = readFileSync(landingPath, 'utf8');
const next = landing.replace(/\/assets\/js\/moon-hero\.js\?v=[0-9a-f]{12}/g, `/assets/js/moon-hero.js?v=${hash}`);
if (next !== landing) writeFileSync(landingPath, next);
console.log(`moon-hero ${hash}: ${(Buffer.byteLength(banner + result.outputFiles[0].text) / 1024).toFixed(1)} KB`);
